def compute_iou(preds, masks, threshold=0.5):
    """Вычисляет IoU (Jaccard) между предсказаниями и масками"""
    preds = (preds > threshold).float()
    intersection = (preds * masks).sum(dim=(1, 2, 3))
    union = ((preds + masks) >= 1).float().sum(dim=(1, 2, 3))
    iou = (intersection + 1e-6) / (union + 1e-6)
    return iou.mean().item()

def evaluate_model(model, dataloader, device):
    """
    Оценивает модель, возвращая средний индекс Жаккара (IoU) по всему даталоадеру.
    """
    model.eval()
    iou_scores = []

    with torch.no_grad():
        for batch in tqdm(dataloader, desc="Evaluating"):
            images = batch[0].to(device)
            masks = batch[1].to(device)

            outputs = model(images)
            preds = torch.sigmoid(outputs)

            iou = compute_iou(preds, masks)
            iou_scores.append(iou)

    return np.mean(iou_scores)

class SegmentationDataset(Dataset):
    def __init__(
        self,
        dataframe,
        transform=None,
    ):
        self.df = dataframe.reset_index(drop=True)
        self.transform = transform

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        # Get image and mask path
        img_path = self.df.loc[idx, "image_path"]
        mask_path = self.df.loc[idx, "mask_path"]

        # Load images
        image = cv2.imread(img_path, cv2.IMREAD_UNCHANGED)
        image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
        mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)

        # Apply Albumentations transform
        if self.transform:
            augmented = self.transform(image=image, mask=mask)
            image = augmented["image"]
            mask = augmented["mask"]
            mask = (mask > 0).float()  # бинаризация маски

        mask = mask.unsqueeze(0)

        return image, mask

    def compute_mean_std(self):

        means = []
        stds = []

