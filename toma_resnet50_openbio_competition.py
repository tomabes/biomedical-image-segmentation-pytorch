def denormalize(tensor, mean, std):
    """
    Преобразует тензор [C, H, W] из нормализованного в исходный диапазон [0, 1]
    """
    mean = torch.tensor(mean).view(-1, 1, 1)
    std = torch.tensor(std).view(-1, 1, 1)
    return tensor * std + mean

